using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using System.Numerics;
using Content.Client.CMU14.Interface.Hud;
using Content.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.UserInterface.Systems.MenuBar.Widgets
{
    // CMU14 class: palette-aware, adaptive menu strip.
    [GenerateTypedNameReferences]
    public sealed partial class GameTopMenuBar : UIWidget
    {
        public GameTopMenuBar()
        {
            RobustXamlLoader.Load(this);
            foreach (var child in MenuGrid.Children)
            {
                if (child is not MenuButton button)
                    continue;
                StyleMenuButton(button);
            }
        }

        protected override void Resized()
        {
            base.Resized();
            UpdateColumns();
        }

        public void AddMenuButton(MenuButton button, MenuButton? before = null)
        {
            StyleMenuButton(button);
            MenuGrid.AddChild(button);
            if (before?.Parent == MenuGrid)
                button.SetPositionInParent(before.GetPositionInParent());
            UpdateColumns();
        }

        private static void StyleMenuButton(MenuButton button)
        {
            // CMU14: retain the authored classes so disabling the new style restores native buttons.
            button.AddStyleClass(CmuHudStyle.MenuButtonClass);
            button.MinSize = new Vector2(42, 64);
        }

        // CMU14: available game width, independent of storage windows.
        public void SetAvailableWidth(float width)
        {
            MenuGrid.Columns = Math.Max(1, Math.Min(MenuGrid.ChildCount, (int) ((width + 4) / 46)));
        }

        private void UpdateColumns() => SetAvailableWidth(Width);
    }
}
