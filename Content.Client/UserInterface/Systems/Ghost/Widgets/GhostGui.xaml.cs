using Content.Client.Stylesheets;
using Content.Client.CMU14.Interface.Hud;
using System.Numerics;
using Content.Client.UserInterface.Systems.Ghost.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.UserInterface.Systems.Ghost.Widgets;

[GenerateTypedNameReferences]
public sealed partial class GhostGui : UIWidget
{
    public GhostTargetWindow TargetWindow { get; }

    public event Action? RequestWarpsPressed;
    public event Action? ReturnToBodyPressed;
    public event Action? GhostRolesPressed;
    public event Action? LateJoinPressed;
    private int _prevNumberRoles;
    private float _availableWidth = float.PositiveInfinity; // CMU14

    public GhostGui()
    {
        RobustXamlLoader.Load(this);

        TargetWindow = new GhostTargetWindow();

        MouseFilter = MouseFilterMode.Ignore;

        GhostWarpButton.OnPressed += _ => RequestWarpsPressed?.Invoke();
        ReturnToBodyButton.OnPressed += _ => ReturnToBodyPressed?.Invoke();
        GhostRolesButton.OnPressed += _ => GhostRolesPressed?.Invoke();
        GhostRolesButton.OnPressed += _ => GhostRolesButton.StyleClasses.Remove(StyleClass.Negative);
        LateJoinButton.OnPressed += _ => LateJoinPressed?.Invoke();
    }

    public void Hide()
    {
        TargetWindow.ClearWarps(clearSearch: true);
        TargetWindow.Close();
        Visible = false;
    }

    // CMU14: native viewport limits and custom editor bounds share the same width-driven flow.
    public void SetAvailableWidth(float width)
    {
        width = MathF.Max(1, width);
        if (_availableWidth == width)
            return;
        _availableWidth = width;
        InvalidateMeasure();
    }

    protected override Vector2 MeasureOverride(Vector2 availableSize) =>
        base.MeasureOverride(new Vector2(CmuHudReflow.IsRoot(this) ? availableSize.X
            : MathF.Min(availableSize.X, _availableWidth), availableSize.Y));

    public float GetMinimumLayoutWidth()
    {
        var width = 1f;
        foreach (var button in GhostButtonGrid.Children)
        {
            button.Measure(new Vector2(float.PositiveInfinity));
            width = MathF.Max(width, button.DesiredSize.X);
        }
        return width;
    }

    public void Update(int? roles, bool? canReturnToBody)
    {
        ReturnToBodyButton.Disabled = !canReturnToBody ?? true;

        if (roles != null)
        {
            GhostRolesButton.Text = Loc.GetString("ghost-gui-ghost-roles-button", ("count", roles));

            if (roles > _prevNumberRoles)
            {
                GhostRolesButton.StyleClasses.Add(StyleClass.Negative);
            }

            _prevNumberRoles = (int)roles;
        }
    }

    [System.Obsolete]
    protected override void Dispose(bool disposing)
    {
        base.Dispose(disposing);

        if (disposing)
        {
            TargetWindow.Close();
        }
    }
}
