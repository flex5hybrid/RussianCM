using Content.Shared.Hands.Components;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.UserInterface.Systems.Hotbar.Widgets;

[GenerateTypedNameReferences]
public sealed partial class HotbarGui : UIWidget
{
    // CMU14: dock geometry consumed by the shared HUD coordinator.
    public float FooterHeight => DesiredSize.Y;
    public float InventoryClearanceHeight =>
        HasVisibleContents(SingleStorageContainer) || HasVisibleContents(LeftStorageContainer) || HasVisibleContents(RightStorageContainer)
            ? FooterHeight
            : Hotbar.DesiredSize.Y;
    public float DockContentLeft => Hotbar.GlobalPosition.X - GlobalPosition.X + Hotbar.ContentLeft;
    public event Action? DockLayoutChanged;

    private static bool HasVisibleContents(BoxContainer container)
    {
        if (!container.VisibleInTree)
            return false;
        foreach (var child in container.Children)
        {
            if (child.VisibleInTree)
                return true;
        }
        return false;
    }
    public HotbarGui()
    {
        RobustXamlLoader.Load(this);
        // CMU14: follow the actual dock-content position.
        Hotbar.ContentPositionChanged += () => DockLayoutChanged?.Invoke();
        StatusPanelRight.SetSide(HandLocation.Right);
        StatusPanelLeft.SetSide(HandLocation.Left);
        var hotbarController = UserInterfaceManager.GetUIController<HotbarUIController>();

        hotbarController.Setup(HandContainer);
        LayoutContainer.SetGrowVertical(this, LayoutContainer.GrowDirection.Begin);
        // CMU14: keep the responsive dock within its layout bounds.
        LayoutContainer.SetGrowHorizontal(this, LayoutContainer.GrowDirection.Constrain);
    }

    // CMU14: adapt hand status and slot columns to viewport width.
    protected override void Resized()
    {
        base.Resized();
        var width = Width < 780 ? 82 : 125;
        if (StatusPanelRight.SetWidth != width)
        {
            StatusPanelRight.SetWidth = width;
            StatusPanelLeft.SetWidth = width;
        }
        HandContainer.ColumnLimit = Width < 520 ? 2 : 6;
    }

    public void UpdatePanelEntityLeft(EntityUid? entity, Hand? hand)
    {
        StatusPanelLeft.Update(entity, hand);
    }

    public void UpdatePanelEntityRight(EntityUid? entity, Hand? hand)
    {
        StatusPanelRight.Update(entity, hand);
    }

    public void SetHighlightHand(HandLocation? hand)
    {
        StatusPanelLeft.UpdateHighlight(hand is HandLocation.Left);
        StatusPanelRight.UpdateHighlight(hand is HandLocation.Right);
    }

    public void UpdateStatusVisibility(bool left, bool right)
    {
        StatusPanelLeft.Visible = left;
        StatusPanelRight.Visible = right;
    }
}
