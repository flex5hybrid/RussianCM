using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.UserInterface.Systems.Inventory.Widgets;

[GenerateTypedNameReferences]
public sealed partial class InventoryGui : UIWidget
{
    public InventoryGui()
    {
        RobustXamlLoader.Load(this);

        var inventoryUIController = UserInterfaceManager.GetUIController<InventoryUIController>();
        inventoryUIController.RegisterInventoryBarContainer(InventoryHotbar);
        // CMU14: keep drawer visibility and its fixed opening toggle in sync.
        InventoryHotbar.OnVisibilityChanged += _ =>
        {
            EquipmentPanel.Visible = InventoryHotbar.Visible;
            // Keep the opening control in place; it is also the close toggle and visual anchor.
            InventoryButton.Highlight = InventoryHotbar.Visible;
        };
        CollapseEquipmentButton.OnPressed += _ => inventoryUIController.ToggleInventoryBar();

        LayoutContainer.SetGrowVertical(this, LayoutContainer.GrowDirection.Begin);
    }

    // CMU14: bound the equipment drawer to the available game area.
    public void SetAvailableHeight(float height)
    {
        EquipmentScroll.MaxHeight = MathF.Max(40, MathF.Min(290, height - 52));
    }

    // CMU14: reserve only visible dock rows and inline storage.
    public void SetDockHeight(float height)
    {
        // The surrounding BoxContainer already provides the gap above the 64px toggle.
        // Reserve additional space only for visible dock rows or open inline storage.
        EquipmentPanel.Margin = new Thickness(0, 0, 0, MathF.Max(0, height - 64));
    }
}
