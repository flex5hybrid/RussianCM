using Content.Shared._CE.Workbench;
using Content.Shared._CE.Workbench.Requirements;
using Content.Shared._RMC14.Chemistry.Reagent;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._CE.Workbench;

[GenerateTypedNameReferences]
public sealed partial class CEWorkbenchRequirementControl : Control
{
    [Dependency] private readonly IEntityManager _entity = default!;
    [Dependency] private readonly IPrototypeManager _proto = default!;

    private readonly SpriteSystem _sprite;

    public CEWorkbenchRequirementControl()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _sprite = _entity.System<SpriteSystem>();
    }

public CEWorkbenchRequirementControl(CEWorkbenchCraftRequirement requirement) : this()
{
    Name.Text = GetRequirementTitle(requirement);

    var texture = requirement.GetRequirementTexture(_proto);
    if (texture is not null)
    {
        View.Visible = true;
        View.Texture = _sprite.Frame0(texture);
        View.Modulate = GetRequirementColor(requirement);
    }

    var entityView = requirement.GetRequirementEntityView(_proto);
    if (entityView is not null)
    {
        EntityView.Visible = true;
        EntityView.Modulate = GetRequirementColor(requirement);
        EntityView.SetPrototype(entityView);
    }
}
private string GetRequirementTitle(CEWorkbenchCraftRequirement requirement)
{
    if (requirement is SolutionResource solutionResource)
    {
        var reagentSystem = _entity.System<RMCReagentSystem>();

        if (!reagentSystem.TryIndex(solutionResource.Reagent, out var reagent))
            return string.Empty;

        return Loc.GetString("ce-workbench-reagent-req",
            ("reagent", reagent.LocalizedName),
            ("count", solutionResource.Amount),
            ("purity", solutionResource.Purity * 100));
    }

    return requirement.GetRequirementTitle(_proto);
}

private Color GetRequirementColor(CEWorkbenchCraftRequirement requirement)
{
    if (requirement is SolutionResource solutionResource)
    {
        var reagentSystem = _entity.System<RMCReagentSystem>();

        if (!reagentSystem.TryIndex(solutionResource.Reagent, out var reagent))
            return Color.White;

        return reagent.SubstanceColor;
    }

    return requirement.GetRequirementColor(_proto);
}
}
