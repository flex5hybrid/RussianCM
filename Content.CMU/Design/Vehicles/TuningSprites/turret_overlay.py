"""Generates the rotating overlay of the homemade turret and of the mounted PKP on it, the way the Humvee turret is drawn:
a sprite of its own over the vehicle, turned to where the turret aims (south, north, east, west), with the middle of
the ring in the middle of the frame. Where on the roof it sits is set per vehicle (CMUVehicleTurretMount in the vehicle
prototypes); the numbers for that are printed by this script from the roof positions in pizza_van.py and vehicles.py.

Run from the repository root:  python -I Content.CMU/Design/Vehicles/TuningSprites/turret_overlay.py [preview.png]
"""
import json
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import png  # noqa: E402
from generate import Canvas, S0, S1, S2, S3, S4, S5, W1, W2, F1, F2, hex_color  # noqa: E402

ROOT = os.getcwd()
OUT_RSI = os.path.join(ROOT, "Content.CMU", "Resources", "Textures", "CMU14", "Objects", "Vehicles",
                       "tuning_turret_overlay.rsi")
SIZE = 48
C = SIZE / 2
# The PKP box magazine.
G1 = hex_color("3b4230")
G2 = hex_color("525a41")


def turret_south():
    """The ring from above, its cradle pointing south (down)."""
    c = Canvas(SIZE, SIZE)
    c.disc(C, C, 7.5, S1)
    c.disc(C, C, 6, S2)
    c.disc(C, C, 7.5, S0, 6.8)
    c.plate(int(C) - 5, int(C) - 3, int(C) - 2, int(C) + 1, W1, W2, S0)
    c.plate(int(C) + 2, int(C) - 5, int(C) + 4, int(C) - 2, S3, S4, S1)
    for i in range(8):
        a = i * math.pi / 4
        c.set(round(C + 6.6 * math.cos(a) - 0.5), round(C + 6.6 * math.sin(a) - 0.5), S5)
    x, y0 = int(C), int(C)
    for rail in (x - 2, x + 1):
        c.rect(rail, y0, rail, y0 + 9, S3)
    c.hline(x - 2, x + 1, y0 + 9, S2)
    c.outline()
    return c


def gun_south():
    """The PKP on the cradle from above, pointing south: stock behind, box magazine on its right, long barrel ahead."""
    c = Canvas(SIZE, SIZE)
    x, y0 = int(C), int(C)
    # Stock and grip behind the ring's middle.
    c.rect(x - 1, y0 - 9, x, y0 - 4, F1)
    c.vline(x - 1, y0 - 9, y0 - 4, F2)
    # Receiver and feed cover.
    c.rect(x - 2, y0 - 4, x + 1, y0 + 4, S0)
    c.vline(x - 1, y0 - 4, y0 + 4, S2)
    # The 200-round box hung on its right side.
    c.plate(x + 2, y0 - 2, x + 5, y0 + 3, G1, G2, S0)
    # Barrel with the gas tube under it, the bipod folded along it, the flash hider at the end.
    c.vline(x - 1, y0 + 5, y0 + 18, S1)
    c.vline(x, y0 + 5, y0 + 14, S2)
    c.rect(x - 2, y0 + 7, x - 2, y0 + 12, S1)
    c.rect(x - 2, y0 + 19, x, y0 + 20, S3)
    c.set(x - 1, y0 + 20, S4)
    c.outline()
    return c


def directions(south):
    """South, north, east and west: the south drawing turned to point each way."""
    north = Canvas(SIZE, SIZE)
    east = Canvas(SIZE, SIZE)
    west = Canvas(SIZE, SIZE)
    for (x, y), color in south.px.items():
        north.set(x, SIZE - 1 - y, color)
        east.set(y, SIZE - 1 - x, color)
        west.set(SIZE - 1 - y, SIZE - 1 - x, color)
    return [south, north, east, west]


STATES = {
    "turret_homemade_0": directions(turret_south()),
    "gun_pkp_0": directions(gun_south()),
}


def save():
    os.makedirs(OUT_RSI, exist_ok=True)
    meta_states = []
    for name, dirs in STATES.items():
        rows = [[(0, 0, 0, 0)] * (SIZE * 2) for _ in range(SIZE * 2)]
        for i, c in enumerate(dirs):
            ox, oy = (i % 2) * SIZE, (i // 2) * SIZE
            for (x, y), color in c.px.items():
                rows[oy + y][ox + x] = color
        png.write(os.path.join(OUT_RSI, name + ".png"), SIZE * 2, SIZE * 2, rows)
        meta_states.append({"name": name, "directions": 4})
    meta = {"version": 1, "license": "CC-BY-SA-3.0",
            "copyright": "Generated by Content.CMU/Design/Vehicles/TuningSprites/turret_overlay.py for CMU, "
                         "palette after the RMC14 vehicle hardpoint icons",
            "size": {"x": SIZE, "y": SIZE}, "states": meta_states}
    with open(os.path.join(OUT_RSI, "meta.json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump(meta, f, indent=2)
        f.write("\n")


# Where the ring sits on each vehicle, in its frame (continuous pixel coordinates, y down): from above facing south and
# north, and from the side facing east; west is east mirrored and shifted like the vehicle's own west frame. The sprite
# offset (pixels, y up, as written in the prototype) and scale of the vehicle's Sprite turn that into the turret's pixel
# offset from the vehicle.
MOUNTS = {
    "VehiclePizzaVan": dict(size=64, south=(31.5, 16.5), north=(31.5, 21.5), east=(27.0, 21.0), west_shift=0,
                            sprite_offset=(0, 16), scale=1.0),
    "AU14VehicleCivTruck": dict(size=96, south=(47.5, 64.5), north=(47.5, 13.5), east=(68.0, 27.0), west_shift=0,
                                sprite_offset=(0, 0), scale=1.0),
    "AU14VehicleCivBlueTruck": dict(size=96, south=(47.5, 49.5), north=(47.5, 22.5), east=(66.0, 26.0), west_shift=0,
                                    sprite_offset=(0, 16), scale=1.0),
    "AU14VehicleCivCar": dict(size=96, south=(47.5, 37.5), north=(47.5, 40.5), east=(40.0, 33.0), west_shift=-2,
                              sprite_offset=(0, 0), scale=1.1),
    "AU14VehicleCivHippieVan": dict(size=96, south=(47.5, 32.5), north=(47.5, 32.5), east=(41.0, 29.0), west_shift=-3,
                                    sprite_offset=(0, 0), scale=1.1),
}


# The vehicle's sprite offset is in the vehicle's own frame and turns with it (the engine multiplies it by the entity's
# rotation): as it is written when the vehicle faces south, upside down when it faces north, a quarter turn either way
# east and west. The turret offset is on screen for each facing, so the sprite offset is turned to match.
TURNS = {"south": lambda x, y: (x, y), "north": lambda x, y: (-x, -y),
         "east": lambda x, y: (-y, x), "west": lambda x, y: (y, -x)}


def offsets(m):
    half = m["size"] / 2
    ex, ey = m["east"]
    points = {"north": m["north"], "east": (ex, ey), "south": m["south"], "west": (m["size"] - ex + m["west_shift"], ey)}
    result = {}
    for name, (fx, fy) in points.items():
        sx, sy = TURNS[name](*m["sprite_offset"])
        ox = (fx - half) * m["scale"] + sx
        oy = (half - fy) * m["scale"] + sy
        result[name] = (round(ox), round(oy))
    return result


def preview(path, scale=6):
    width, height = 4 * SIZE * scale, 2 * SIZE * scale
    rows = [[(200, 200, 200, 255) if ((x // 12 + y // 12) % 2) else (225, 225, 225, 255) for x in range(width)]
            for y in range(height)]
    for r, combo in enumerate(([STATES["turret_homemade_0"]], [STATES["turret_homemade_0"], STATES["gun_pkp_0"]])):
        for d in range(4):
            for dirs in combo:
                for (x, y), color in dirs[d].px.items():
                    for dy in range(scale):
                        for dx in range(scale):
                            rows[r * SIZE * scale + y * scale + dy][d * SIZE * scale + x * scale + dx] = color
    png.write(path, width, height, rows)


def main():
    save()
    for vehicle, m in MOUNTS.items():
        o = offsets(m)
        print(vehicle, " ".join(f"{k}={v[0]},{v[1]}" for k, v in o.items()))
    if len(sys.argv) > 1:
        preview(sys.argv[1])


if __name__ == "__main__":
    main()
