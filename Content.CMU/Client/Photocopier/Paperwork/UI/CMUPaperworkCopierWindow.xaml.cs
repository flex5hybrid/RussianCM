using System.IO;
using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared.CMU14.Photocopier.Paperwork;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.ContentPack;
using Robust.Shared.Maths;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client.CMU14.Photocopier.Paperwork.UI;

[GenerateTypedNameReferences]
public sealed partial class CMUPaperworkCopierWindow : FancyWindow
{
    private enum Tab
    {
        Copy,
        Forms,
    }

    private static readonly Color PaperColor = Color.FromHex("#d8d2bd");
    private static readonly Color PaperTextColor = Color.FromHex("#1b1b1b");
    private static readonly Color HintColor = Color.FromHex("#4d4d4d");
    private static readonly Color ReadyColor = Color.FromHex("#4caf50");
    private static readonly Color BusyColor = Color.FromHex("#e0a030");
    private static readonly Color ErrorColor = Color.FromHex("#d05050");

    private readonly IPrototypeManager _protoManager;
    private readonly IResourceManager _resources;
    private readonly Dictionary<CMUPaperworkFormCategory, Button> _factionButtons = new();
    private readonly Dictionary<string, string> _formTextCache = new();

    public event Action<ProtoId<CMUPaperworkFormPrototype>>? FormSelected;
    public event Action<CMUPaperworkCopierMode>? PrintRequested;

    private CMUPaperworkCopierUiState? _state;
    private HashSet<CMUPaperworkFormCategory> _allowedFactions = [];
    private CMUPaperworkFormCategory? _faction;
    private ProtoId<CMUPaperworkFormPrototype>? _chosenForm;
    private Button? _selectedFormButton;
    private Tab _tab = Tab.Forms;
    private bool _tabInitialized;
    private bool _wasPaperInserted;
    private float _busyRemaining;
    private float _busyTotal;

    public CMUPaperworkCopierWindow(IPrototypeManager protoManager)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _protoManager = protoManager;
        _resources = IoCManager.Resolve<IResourceManager>();

        PreviewPanel.PanelOverride = new StyleBoxFlat { BackgroundColor = PaperColor };
        CopyHint.SetMessage(FormattedMessage.FromUnformatted(Loc.GetString("cmu-paperwork-copier-ui-copy-hint")));

        CopyTabButton.OnPressed += _ => SetTab(Tab.Copy);
        FormsTabButton.OnPressed += _ => SetTab(Tab.Forms);
        ActionButton.OnPressed += _ => OnActionPressed();
        SearchBar.OnTextChanged += _ => PopulateForms();

        SetTab(Tab.Forms);
    }

    public void UpdateState(CMUPaperworkCopierUiState state)
    {
        _state = state;
        _chosenForm = state.ChosenForm;
        _allowedFactions = state.AllowedFormCategories;
        _busyRemaining = state.BusyRemaining;
        _busyTotal = state.BusyTotal;

        if (!_tabInitialized)
        {
            _tabInitialized = true;
            SetTab(state.IsPaperInserted ? Tab.Copy : Tab.Forms);
        }
        else if (state.IsPaperInserted && !_wasPaperInserted)
        {
            SetTab(Tab.Copy);
        }

        _wasPaperInserted = state.IsPaperInserted;

        UpdateStatus(state);
        UpdatePaperLabel(state);
        PopulateFactions();
        PopulateForms();
        UpdatePreview();
        UpdateActionButton();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_busyRemaining <= 0)
            return;

        _busyRemaining = Math.Max(0f, _busyRemaining - args.DeltaSeconds);
        UpdateProgress();
    }

    private IEnumerable<CMUPaperworkFormPrototype> AllForms => _protoManager.EnumeratePrototypes<CMUPaperworkFormPrototype>();

    private void SetTab(Tab tab)
    {
        _tab = tab;

        CopyPanel.Visible = tab == Tab.Copy;
        FormsPanel.Visible = tab == Tab.Forms;
        CopyTabButton.Pressed = tab == Tab.Copy;
        FormsTabButton.Pressed = tab == Tab.Forms;

        UpdatePreview();
        UpdateActionButton();
    }

    private void UpdateStatus(CMUPaperworkCopierUiState state)
    {
        string key;
        Color color;

        if (!state.IsPowered)
        {
            key = "cmu-paperwork-copier-ui-status-unpowered";
            color = ErrorColor;
        }
        else
        {
            switch (state.Stage)
            {
                case CMUPaperworkCopierStage.Scanning:
                    key = "cmu-paperwork-copier-ui-status-scanning";
                    color = BusyColor;
                    break;
                case CMUPaperworkCopierStage.Printing:
                    key = "cmu-paperwork-copier-ui-status-printing";
                    color = BusyColor;
                    break;
                case CMUPaperworkCopierStage.Cooldown:
                    key = "cmu-paperwork-copier-ui-status-cooldown";
                    color = BusyColor;
                    break;
                default:
                    key = "cmu-paperwork-copier-ui-status-ready";
                    color = ReadyColor;
                    break;
            }
        }

        StatusLabel.Text = Loc.GetString(key);
        StatusLabel.FontColorOverride = color;
        UpdateProgress();
    }

    private void UpdateProgress()
    {
        var busy = _busyRemaining > 0 && _state is { IsPowered: true };
        BusyBar.Visible = busy;

        if (busy)
            BusyBar.Value = _busyTotal > 0 ? Math.Clamp(1f - _busyRemaining / _busyTotal, 0f, 1f) : 1f;
    }

    private void UpdatePaperLabel(CMUPaperworkCopierUiState state)
    {
        PaperLabel.Text = state.InsertedPaperName is { } name
            ? Loc.GetString("cmu-paperwork-copier-ui-paper-inserted", ("name", name))
            : Loc.GetString("cmu-paperwork-copier-ui-paper-missing");
    }

    private void PopulateFactions()
    {
        FactionGrid.RemoveAllChildren();
        _factionButtons.Clear();

        var factions = AllForms
            .Where(p => _allowedFactions.Contains(p.Category))
            .GroupBy(p => p.Category)
            .OrderBy(g => g.Key)
            .ToList();

        if (_faction is { } current && factions.All(g => g.Key != current))
            _faction = null;

        foreach (var group in factions)
        {
            var faction = group.Key;
            var button = new Button
            {
                Text = Loc.GetString("cmu-paperwork-copier-faction-" + faction) + " (" + group.Count() + ")",
                ToggleMode = true,
                Pressed = _faction == faction,
                HorizontalExpand = true,
            };

            button.OnPressed += _ => SelectFaction(faction);
            _factionButtons[faction] = button;
            FactionGrid.AddChild(button);
        }
    }

    private void SelectFaction(CMUPaperworkFormCategory faction)
    {
        _faction = _faction == faction ? null : faction;

        foreach (var (key, button) in _factionButtons)
        {
            button.Pressed = key == _faction;
        }

        PopulateForms();
    }

    private void PopulateForms()
    {
        FormList.RemoveAllChildren();
        _selectedFormButton = null;

        var search = SearchBar.Text.Trim();

        var forms = AllForms
            .Where(p => _allowedFactions.Contains(p.Category))
            .Where(p => _faction == null || p.Category == _faction)
            .Select(p => (Proto: p, Name: GetFormName(p)))
            .Where(f => search.Length == 0 || f.Name.Contains(search, StringComparison.CurrentCultureIgnoreCase))
            .OrderBy(f => f.Name, StringComparer.CurrentCultureIgnoreCase)
            .ToList();

        ResultsLabel.Text = Loc.GetString("cmu-paperwork-copier-ui-results", ("count", forms.Count));

        if (forms.Count == 0)
        {
            FormList.AddChild(new Label { Text = Loc.GetString("cmu-paperwork-copier-ui-no-forms") });
            return;
        }

        foreach (var (proto, name) in forms)
        {
            var button = new Button
            {
                Text = name,
                ToggleMode = true,
                Pressed = _chosenForm is { } chosen && chosen.Id == proto.ID,
            };

            if (button.Pressed)
                _selectedFormButton = button;

            button.OnPressed += _ => SelectForm(button, proto.ID);
            FormList.AddChild(button);
        }
    }

    private void SelectForm(Button button, ProtoId<CMUPaperworkFormPrototype> form)
    {
        if (_selectedFormButton != null && _selectedFormButton != button)
            _selectedFormButton.Pressed = false;

        _selectedFormButton = button;
        _chosenForm = form;
        button.Pressed = true;

        UpdatePreview();
        UpdateActionButton();
        FormSelected?.Invoke(form);
    }

    private void UpdatePreview()
    {
        var state = _state;

        if (_tab == Tab.Copy)
        {
            if (state == null || state.InsertedPaperName == null)
            {
                ShowHint("cmu-paperwork-copier-ui-preview-title-no-paper", "cmu-paperwork-copier-ui-copy-empty");
                return;
            }

            PreviewTitle.Text = state.InsertedPaperName;
            ShowMarkup(state.InsertedPaperContent ?? string.Empty);
            return;
        }

        if (_chosenForm is { } chosen && _protoManager.TryIndex(chosen, out var form))
        {
            PreviewTitle.Text = GetFormName(form);

            var text = ReadFormText(form);
            if (text == null)
                ShowHintText(Loc.GetString("cmu-paperwork-copier-ui-form-missing"));
            else
                ShowMarkup(text);

            return;
        }

        ShowHint("cmu-paperwork-copier-ui-preview-title-no-form", "cmu-paperwork-copier-ui-form-empty");
    }

    private void ShowHint(string titleKey, string hintKey)
    {
        PreviewTitle.Text = Loc.GetString(titleKey);
        ShowHintText(Loc.GetString(hintKey));
    }

    private void ShowHintText(string text)
    {
        PreviewText.SetMessage(FormattedMessage.FromUnformatted(text), defaultColor: HintColor);
    }

    private void ShowMarkup(string text)
    {
        PreviewText.SetMessage(FormattedMessage.FromMarkupPermissive(text), defaultColor: PaperTextColor);
    }

    private string? ReadFormText(CMUPaperworkFormPrototype form)
    {
        if (_formTextCache.TryGetValue(form.ID, out var cached))
            return cached;

        if (!_resources.TryContentFileRead(form.Text, out var stream))
            return null;

        using var reader = new StreamReader(stream);
        var text = reader.ReadToEnd();
        _formTextCache[form.ID] = text;
        return text;
    }

    private void UpdateActionButton()
    {
        var state = _state;
        var canWork = state != null && state.CanPrint;

        if (_tab == Tab.Copy)
        {
            ActionButton.Text = Loc.GetString("cmu-paperwork-copier-ui-copy-button");
            ActionButton.Disabled = !canWork || !state!.IsPaperInserted;
        }
        else
        {
            ActionButton.Text = Loc.GetString("cmu-paperwork-copier-ui-print-button");
            ActionButton.Disabled = !canWork || _chosenForm == null;
        }
    }

    private void OnActionPressed()
    {
        ActionButton.Disabled = true;
        PrintRequested?.Invoke(_tab == Tab.Copy ? CMUPaperworkCopierMode.Copy : CMUPaperworkCopierMode.Print);
    }

    private string GetFormName(CMUPaperworkFormPrototype form)
    {
        return Loc.TryGetString(form.Name, out var name) ? name : form.Name;
    }
}
